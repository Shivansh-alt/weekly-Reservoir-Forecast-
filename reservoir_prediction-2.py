# ==========================================
# 1. IMPORT LIBRARIES
# ==========================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from google.colab import files

from sklearn.model_selection import (
    train_test_split,
    KFold,
    cross_validate
)

from sklearn.pipeline import make_pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import (
    PolynomialFeatures,
    StandardScaler
)

from sklearn.linear_model import LinearRegression, Ridge
from sklearn.neighbors import KNeighborsRegressor
from sklearn.dummy import DummyRegressor

from sklearn.metrics import (
    mean_squared_error,
    mean_absolute_error,
    r2_score
)

print("Libraries imported successfully.")

"""# Uploading and Reading the File"""

uploaded = files.upload()

df = pd.read_csv(next(iter(uploaded.keys())))

df.columns = df.columns.str.strip()

print("Dataset shape:", df.shape)

print("\nColumn names:")
print(df.columns.tolist())

print("\nFirst five rows:")
display(df.head())

"""# Selecting feature and Target"""

target_column = "THIS YEAR LIVE STORAGE (BCM)"

feature_columns = [
    "LIVE CAP. AT FRL (BCM)",
    "THIS SEASON LEVEL (MTS)",
    "LAST YEAR LIVE STORAGE (BCM)",
    "Normal Storage (BCM)"
]

# Check whether required columns exist
required_columns = feature_columns + [target_column]

missing_columns = [
    col for col in required_columns if col not in df.columns
]

if missing_columns:
    raise ValueError(
        f"Missing columns in dataset: {missing_columns}"
    )

# Select required columns
data = df[required_columns].copy()

# Convert columns into numeric format
for col in required_columns:
    data[col] = pd.to_numeric(
        data[col],
        errors="coerce"
    )

# Remove rows where target is missing
data = data.dropna(
    subset=[target_column]
).reset_index(drop=True)

# Check duplicate rows
print("Duplicate rows:", data.duplicated().sum())

# Separate features and target
X = data[feature_columns]
y = data[target_column]

print("\nCleaned dataset shape:", data.shape)

print("\nMissing values:")
display(data.isnull().sum())

print("\nFeature variables:")
print(feature_columns)

print("\nTarget variable:")
print(target_column)

"""# Exploratory Data Analysis (EDA)"""

# 1. Statistical summary
print("STATISTICAL SUMMARY")

display(data.describe().round(3))


# 2. Missing value analysis
print("\nMISSING VALUES")

missing_values = data.isnull().sum()

display(missing_values)


# 3. Distribution of target variable
plt.figure(figsize=(8, 5))

plt.hist(
    y,
    bins=10,
    edgecolor="black"
)

plt.title("Distribution of Reservoir Live Storage")
plt.xlabel("Live Storage (BCM)")
plt.ylabel("Frequency")
plt.grid(alpha=0.3)

plt.show()


# 4. Boxplot to inspect possible outliers
plt.figure(figsize=(8, 4))

plt.boxplot(y.dropna())

plt.title("Reservoir Live Storage - Boxplot")
plt.ylabel("Live Storage (BCM)")
plt.grid(alpha=0.3)

plt.show()


# 5. Correlation matrix
correlation_matrix = data.corr(numeric_only=True)

plt.figure(figsize=(9, 7))

plt.imshow(
    correlation_matrix,
    aspect="auto"
)

plt.colorbar(label="Correlation")

plt.xticks(
    range(len(correlation_matrix.columns)),
    correlation_matrix.columns,
    rotation=90
)

plt.yticks(
    range(len(correlation_matrix.columns)),
    correlation_matrix.columns
)

plt.title("Correlation Matrix")

plt.tight_layout()
plt.show()


# 6. Relationship between each feature and target
for col in feature_columns:

    plt.figure(figsize=(7, 4))

    plt.scatter(
        data[col],
        y
    )

    plt.xlabel(col)
    plt.ylabel(target_column)

    plt.title(f"{col} vs Reservoir Live Storage")

    plt.grid(alpha=0.3)
    plt.show()

"""# SPLIT DATA INTO TRAINING AND TESTING SETS"""

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

print("Training records:", len(X_train))
print("Testing records:", len(X_test))

"""# DEFINE REGRESSION MODELS"""

models = {

    "Baseline (Mean)": make_pipeline(
        SimpleImputer(strategy="median"),
        DummyRegressor(strategy="mean")
    ),

    "Linear Regression": make_pipeline(
        SimpleImputer(strategy="median"),
        StandardScaler(),
        LinearRegression()
    ),

    "Polynomial Regression": make_pipeline(
        SimpleImputer(strategy="median"),
        PolynomialFeatures(
            degree=2,
            include_bias=False
        ),
        StandardScaler(),
        LinearRegression()
    ),

    "Ridge Regression": make_pipeline(
        SimpleImputer(strategy="median"),
        StandardScaler(),
        Ridge(alpha=1.0)
    ),

    "KNN Regression": make_pipeline(
        SimpleImputer(strategy="median"),
        StandardScaler(),
        KNeighborsRegressor(n_neighbors=5)
    )

}

print("Models defined successfully.")

for name in models:
    print("-", name)

"""# CROSS VALIDATION"""

# ==========================================
# 7. 5-FOLD CROSS VALIDATION
# ==========================================

cv = KFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)

cv_results = []

scoring_metrics = {
    "RMSE": "neg_root_mean_squared_error",
    "MAE": "neg_mean_absolute_error",
    "R2": "r2"
}

for name, model in models.items():

    scores = cross_validate(
        model,
        X_train,
        y_train,
        cv=cv,
        scoring=scoring_metrics
    )

    cv_results.append({

        "Model": name,

        "CV_RMSE_Mean": -scores["test_RMSE"].mean(),

        "CV_RMSE_STD": scores["test_RMSE"].std(),

        "CV_MAE_Mean": -scores["test_MAE"].mean(),

        "CV_R2_Mean": scores["test_R2"].mean()

    })


cv_results_df = pd.DataFrame(cv_results)

cv_results_df = cv_results_df.sort_values(
    by="CV_RMSE_Mean"
)

print("CROSS-VALIDATION RESULTS")

display(cv_results_df.round(4))



"""#  TRAIN, PREDICT, AND EVALUATE"""

# ==========================================
# 8. TRAIN AND TEST MODEL PERFORMANCE
# ==========================================

results = []

predictions = pd.DataFrame({

    "Actual_Storage_BCM": y_test.to_numpy()

}, index=y_test.index)


for name, model in models.items():

    # Train model
    model.fit(X_train, y_train)

    # Predict
    y_pred = model.predict(X_test)

    # Calculate metrics
    rmse = np.sqrt(
        mean_squared_error(y_test, y_pred)
    )

    mae = mean_absolute_error(
        y_test,
        y_pred
    )

    r2 = r2_score(
        y_test,
        y_pred
    )

    results.append({

        "Model": name,
        "Test_RMSE": rmse,
        "Test_MAE": mae,
        "Test_R2": r2

    })

    predictions[name + "_Prediction"] = y_pred

    print(f"\n--- {name} ---")

    print(f"RMSE: {rmse:.4f}")
    print(f"MAE:  {mae:.4f}")
    print(f"R2:   {r2:.4f}")


# Combine cross-validation and test results
test_results_df = pd.DataFrame(results)

final_results = cv_results_df.merge(
    test_results_df,
    on="Model"
)

final_results = final_results.sort_values(
    by="CV_RMSE_Mean"
)

print("\nFINAL MODEL COMPARISON")

display(final_results.round(4))

predictions = predictions.sort_index()

print("\nMODEL PREDICTIONS")

display(predictions.round(4))

"""# Visualisation of model Performance"""

# Improved model comparison graph

plot_data = cv_results_df.sort_values(
    "CV_RMSE_Mean",
    ascending=True
)

plt.figure(figsize=(10, 6))

bars = plt.barh(
    plot_data["Model"],
    plot_data["CV_RMSE_Mean"]
)

plt.xscale("log")

plt.xlabel("Cross-Validation RMSE (log scale)")
plt.ylabel("Regression Models")

plt.title("Comparison of Regression Models")

for bar, value in zip(
    bars,
    plot_data["CV_RMSE_Mean"]
):
    plt.text(
        value * 1.05,
        bar.get_y() + bar.get_height()/2,
        f"{value:.4f}",
        va="center"
    )

plt.grid(axis="x", alpha=0.3)

plt.tight_layout()
plt.show()

"""# MODEL INTERPRETATION"""

# ==========================================
# 10. MODEL INTERPRETATION
# ==========================================

linear_model = models["Linear Regression"]

# Extract trained Linear Regression model
regression_step = linear_model.named_steps[
    "linearregression"
]

coefficients = regression_step.coef_

# Create interpretation table
interpretation_df = pd.DataFrame({

    "Feature": feature_columns,

    "Standardized_Coefficient": coefficients

})

interpretation_df["Absolute_Impact"] = (
    interpretation_df["Standardized_Coefficient"].abs()
)

interpretation_df = interpretation_df.sort_values(
    by="Absolute_Impact",
    ascending=False
)

print("LINEAR REGRESSION FEATURE INTERPRETATION")

display(interpretation_df.round(4))


# Feature coefficient visualisation
plt.figure(figsize=(9, 5))

plt.barh(
    interpretation_df["Feature"],
    interpretation_df["Standardized_Coefficient"]
)

plt.xlabel("Standardized Coefficient")

plt.ylabel("Features")

plt.title("Feature Influence - Linear Regression")

plt.grid(axis="x", alpha=0.3)

plt.tight_layout()
plt.show()

"""#  CREATE FINAL CSV FILES"""

# ==========================================
# 11. EXPORT FINAL RESULTS
# ==========================================

# 1. Complete model comparison
final_results.to_csv(
    "model_comparison_improved.csv",
    index=False
)


# 2. Actual and predicted values
predictions.to_csv(
    "model_predictions_improved.csv",
    index_label="Original_Row_Index"
)


# 3. Cross-validation results
cv_results_df.to_csv(
    "cross_validation_results.csv",
    index=False
)


# 4. Feature interpretation
interpretation_df.to_csv(
    "feature_interpretation.csv",
    index=False
)


# 5. Cleaned dataset
data.to_csv(
    "cleaned_reservoir_dataset.csv",
    index=False
)


print("All CSV files generated successfully.")


